import { describePlan, formScore, formatDuration, type SessionSummary } from '../../state/session';
import { currentWeight, formatChange, formatWeight, parseDay, sortEntries, type BodyData } from '../../state/body';
import styles from './PrintLog.module.css';

/**
 * A plain, readable workout log. Hidden on screen; it's what gets printed
 * when the user presses "Download PDF" (the browser's "Save as PDF").
 */
export function PrintLog({ history, title, body }: { history: SessionSummary[]; title: string; body?: BodyData }) {
  const totalReps = history.reduce((s, h) => s + h.totals.reps, 0);
  const totalHold = history.reduce((s, h) => s + h.totals.holdMs, 0);
  const scores = history.map((h) => formScore(h.kind, h.totals)).filter((x): x is number => x !== null);
  const avgScore = scores.length ? Math.round(scores.reduce((a, b) => a + b, 0) / scores.length) : null;
  const dates = history.map((h) => h.date).sort();
  const fmt = (iso: string) => new Date(iso).toLocaleDateString(undefined, { dateStyle: 'medium' });

  return (
    <div className={`print-only print-area ${styles.log}`}>
      <h1>Kinematic workout log</h1>
      <p className={styles.meta}>
        {title}
        {dates.length > 0 && ` · ${fmt(dates[0])} – ${fmt(dates[dates.length - 1])}`} · printed{' '}
        {new Date().toLocaleDateString(undefined, { dateStyle: 'medium' })}
      </p>

      <table className={styles.summary}>
        <tbody>
          <tr>
            <td>Workouts</td>
            <td>{history.length}</td>
            <td>Total reps</td>
            <td>{totalReps}</td>
            <td>Total time held</td>
            <td>{formatDuration(totalHold / 1000)}</td>
            <td>Avg form score</td>
            <td>{avgScore ?? '–'}</td>
          </tr>
        </tbody>
      </table>

      <table className={styles.table}>
        <thead>
          <tr>
            <th>Date</th>
            <th>Exercise</th>
            <th>Plan</th>
            <th>Sets</th>
            <th>Total</th>
            <th>Form score</th>
            <th>Duration</th>
          </tr>
        </thead>
        <tbody>
          {history.map((h) => {
            const hold = h.kind === 'hold';
            return (
              <tr key={h.id}>
                <td>{new Date(h.date).toLocaleString(undefined, { dateStyle: 'medium', timeStyle: 'short' })}</td>
                <td>
                  {h.exerciseName}
                  {h.routine ? ` (${h.routine.name})` : ''}
                </td>
                <td>{describePlan(h.kind, h.plan)}</td>
                <td>{h.sets.map((s) => (hold ? formatDuration(s.stats.holdMs / 1000) : s.stats.reps)).join(', ')}</td>
                <td>{hold ? `${formatDuration(h.totals.holdMs / 1000)} held` : `${h.totals.reps} reps`}</td>
                <td>{formScore(h.kind, h.totals) ?? '–'}</td>
                <td>{formatDuration(h.durationSec)}</td>
              </tr>
            );
          })}
        </tbody>
      </table>
      {body?.goal && <BodySection body={body} />}
      <p className={styles.footer}>Generated by Kinematic · kinematic-one.vercel.app</p>
    </div>
  );
}

function BodySection({ body }: { body: BodyData }) {
  const goal = body.goal;
  if (!goal) return null;
  const unit = body.unit;
  const entries = sortEntries(body.entries).reverse();
  const current = currentWeight(body) ?? goal.startWeightKg;
  const names = { lose: 'Lose weight', gain: 'Gain weight', maintain: 'Maintain weight' };
  return (
    <div className={styles.bodySection}>
      <h2>Body weight</h2>
      <p className={styles.meta}>
        Goal: {names[goal.type]} · start {formatWeight(goal.startWeightKg, unit)} · now {formatWeight(current, unit)} (
        {formatChange(current - goal.startWeightKg, unit)}) · goal {formatWeight(goal.goalWeightKg, unit)}
      </p>
      <table className={styles.table}>
        <thead>
          <tr>
            <th>Date</th>
            <th>Weight</th>
            <th>Change</th>
          </tr>
        </thead>
        <tbody>
          {entries.map((e, i) => (
            <tr key={e.id}>
              <td>{parseDay(e.date).toLocaleDateString(undefined, { dateStyle: 'medium' })}</td>
              <td>{formatWeight(e.weightKg, unit)}</td>
              <td>{entries[i + 1] ? formatChange(e.weightKg - entries[i + 1].weightKg, unit) : 'start'}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}
